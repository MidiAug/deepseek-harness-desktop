#!/usr/bin/env node
/** Concat inject modules → src-tauri/inject/bundle.js */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const injectDir = path.join(root, "src-tauri/inject");

const ORDER = [
  "00-guard.js",
  "01-kernel.js",
  "02-selectors.js",
  "services/dom-utils.js",
  "services/clipboard.js",
  "services/text-edit.js",
  "services/zone-resolver.js",
  "services/selection-scope.js",
  "services/sidebar-proxy.js",
  "services/hygiene.js",
  "services/sidebar-probe.js",
  "services/session-log.js",
  "features/hygiene.js",
  "features/sidebar-probe.js",
  "features/session-log.js",
  "features/menu.js",
];

const parts = [
  "/* B49 inject bundle — generated by scripts/bundle-inject.mjs */\n",
];
for (const rel of ORDER) {
  const full = path.join(injectDir, rel);
  if (!fs.existsSync(full)) {
    console.error("missing:", rel);
    process.exit(1);
  }
  const src = fs.readFileSync(full, "utf8");
  parts.push(`\n/* --- ${rel} --- */\n${src}\n`);
}

const out = path.join(injectDir, "bundle.js");
fs.writeFileSync(out, parts.join(""));
console.log("wrote", out, parts.join("").length, "chars");
